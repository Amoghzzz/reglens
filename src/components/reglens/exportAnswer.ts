import type { Turn } from './types';
import { LEGAL_NOTICE, buildNotes, docTitleOf, formatDate, noteKey, pageSuffix, segments, toBlocks } from './format';

/** Replaces inline citations with [n] markers and returns the numbered source list. */
function prepare(turn: Turn) {
  const text = turn.answer.replace(LEGAL_NOTICE, '').trim();
  const blocks = toBlocks(text);
  const { keyToN, notes } = buildNotes(blocks, turn);
  const lineText = (line: string) =>
    segments(line)
      .map((seg) => {
        if (seg.t === 'text') return seg.v;
        if (seg.t === 'bold') return seg.v;
        return seg.parts
          .map((p) => keyToN.get(noteKey(p)))
          .filter(Boolean)
          .map((n) => `[${n}]`)
          .join('');
      })
      .join('')
      .replace(/\s+(\[\d+\])/g, ' $1')
      .trim();
  return { blocks, notes, lineText };
}

function sourceLine(n: { n: number; title: string; part: { para: string }; page: string; verified: boolean }) {
  return `[${n.n}] ${n.title}, para ${n.part.para}${pageSuffix(n.page)}${n.verified ? '' : ' (not verified)'}`;
}

/** Plain-text version for pasting into an email, note or ticket. */
export function answerAsText(turn: Turn): string {
  const { blocks, notes, lineText } = prepare(turn);
  const out: string[] = [`Q: ${turn.question}`, ''];
  for (const b of blocks) {
    if (b.kind === 'h') out.push('', b.lines[0].toUpperCase());
    else if (b.kind === 'p') out.push(lineText(b.lines[0]));
    else b.lines.forEach((l, i) => out.push(`${b.kind === 'ol' ? `${i + 1}.` : '-'} ${lineText(l)}`));
  }
  if (notes.length) {
    out.push('', 'SOURCES');
    notes.forEach((n) => out.push(sourceLine(n)));
  }
  out.push('', `Generated by RegLens on ${new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}. ${LEGAL_NOTICE}`);
  return out.join('\n');
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Opens a clean, print-ready memo in a new window and starts the browser's Print / Save as PDF dialog. */
export function printMemo(turn: Turn, profileLabel?: string): boolean {
  const { blocks, notes, lineText } = prepare(turn);
  const body = blocks
    .map((b) => {
      if (b.kind === 'h') return `<h2>${esc(b.lines[0])}</h2>`;
      if (b.kind === 'p') return `<p>${esc(lineText(b.lines[0]))}</p>`;
      const tag = b.kind === 'ol' ? 'ol' : 'ul';
      return `<${tag}>${b.lines.map((l) => `<li>${esc(lineText(l))}</li>`).join('')}</${tag}>`;
    })
    .join('\n');
  const sources = notes
    .map(
      (n) => `<li><strong>${esc(n.title)}</strong>, paragraph ${esc(n.part.para)}${esc(pageSuffix(n.page))}${
        n.result?.chunk.date ? ` <span class="muted">(version updated ${esc(formatDate(n.result.chunk.date))})</span>` : ''
      }${n.verified ? '' : ' <span class="warn">Not verified</span>'}${
        n.support && n.support.verdict !== 'supported'
          ? ` <span class="warn">${n.support.verdict === 'partial' ? 'Partly supported' : 'Not supported'}</span>`
          : ''
      }${n.excerpt ? `<blockquote>${esc(n.excerpt)}</blockquote>` : ''}</li>`,
    )
    .join('\n');
  const date = new Date().toLocaleString('en-IN', { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' });
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>RegLens memo: ${esc(turn.question.slice(0, 80))}</title>
<style>
  @page { margin: 18mm 16mm; }
  body { font: 11.5pt/1.55 Georgia, 'Times New Roman', serif; color: #142033; max-width: 720px; margin: 24px auto; padding: 0 16px; }
  header { border-bottom: 2px solid #0e7c66; padding-bottom: 10px; margin-bottom: 18px; font-family: system-ui, sans-serif; }
  header .brand { font-weight: 700; color: #0a5c4c; font-size: 10pt; }
  header .meta { color: #6b7685; font-size: 9pt; margin-top: 2px; }
  h1 { font: 600 17pt/1.3 system-ui, sans-serif; margin: 10px 0 0; }
  h2 { font: 600 11pt system-ui, sans-serif; margin: 18px 0 6px; color: #0a5c4c; }
  p, li { margin: 0 0 8px; }
  ol.sources { padding-left: 22px; font-size: 10pt; }
  blockquote { margin: 4px 0 10px; padding: 4px 10px; border-left: 3px solid #f5d46b; background: #fffbea; font-style: italic; }
  .muted { color: #6b7685; } .warn { color: #b45309; font-weight: 600; font-family: system-ui, sans-serif; font-size: 9pt; }
  footer { margin-top: 24px; border-top: 1px solid #ddd; padding-top: 8px; font: 8.5pt system-ui, sans-serif; color: #6b7685; }
</style></head><body>
<header><div class="brand">RegLens · RBI Master Directions for NBFCs</div>
<div class="meta">Prepared ${esc(date)}${profileLabel ? ` · For: ${esc(profileLabel)}` : ''}</div>
<h1>${esc(turn.question)}</h1></header>
${body}
${notes.length ? `<h2>Sources</h2><ol class="sources">${sources}</ol>` : ''}
<footer>Answers are drawn only from the RBI Master Directions RegLens has indexed, with each citation checked against the source text. ${LEGAL_NOTICE} Check the original Direction before acting.</footer>
<script>window.onload = () => setTimeout(() => window.print(), 300);</script>
</body></html>`;
  const w = window.open('', '_blank');
  if (!w) return false;
  w.document.open();
  w.document.write(html);
  w.document.close();
  return true;
}

export function docLabel(turn: Turn): string {
  return turn.results[0] ? docTitleOf(turn.results[0].chunk) : '';
}
